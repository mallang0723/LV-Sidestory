// Generates src/generated/side-story-app.js from the verbatim upstream sources in upstream/.
// Same idea as upstream build.py: every upstream file is concatenated into one async function so the
// files share one scope. Upstream wraps it for SillyTavern with st-host.js; this wraps it for
// Lumiverse with src/lumiverse/host.js (passed in as `stHost`), a prelude of name shims and the glue.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {applyPatches,PATCHES} from '../src/lumiverse/patches.mjs';
import {toContainerQueries} from '../src/lumiverse/css-transform.mjs';
import {phoneFloor} from '../src/lumiverse/css-floor.mjs';

const root=new URL('..',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');

export function buildApp(){
 // Follow upstream's own file order so an upstream update needs no change here.
 const order=JSON.parse(read('upstream/build.py').match(/files=(\[[^\]]*\])/)[1].replace(/'/g,'"'));
 const sources=Object.fromEntries(order.map(f=>[f,read('upstream/src/'+f)]));
 const patched=applyPatches(sources);
 const style=toContainerQueries(read('upstream/src/style.css'));
 if(style.selfTargets.length)throw Error('container query cannot style .app itself: '+style.selfTargets.join(', '));
 const css=style.css+'\n'+phoneFloor(style.css)+'\n'+read('src/lumiverse/style.css');
 const digest=createHash('sha256');for(const f of [...order,'style.css'])digest.update(f+'\0'+read('upstream/src/'+f));
 const code=[
  '// GENERATED by scripts/build-app.mjs — do not edit. Sources: upstream/src (ST-Sidestory 0.17.0, verbatim),',
  `// src/lumiverse/patches.mjs (${PATCHES.length} documented patches), src/lumiverse/prelude.inc.js, src/lumiverse/glue.inc.js, src/lumiverse/css-floor.mjs, src/lumiverse/style.css.`,
  `// upstream digest ${digest.digest('hex')}`,
  '/* eslint-disable */',
  'export async function runSideStory(stHost){',
  read('src/lumiverse/prelude.inc.js'),
  'const SIDE_STYLE='+JSON.stringify(css)+';',
  ...order.map(f=>`// ---- upstream/src/${f}\n`+patched[f]),
  '// ---- src/lumiverse/glue.inc.js',
  read('src/lumiverse/glue.inc.js'),
  '}',
  ''
 ].join('\n');
 return code;
}

if(import.meta.url===`file://${process.argv[1]}`){
 const code=buildApp();
 mkdirSync(new URL('src/generated/',root),{recursive:true});
 const target=new URL('src/generated/side-story-app.js',root);
 if(process.argv.includes('--check')){
  if(readFileSync(target,'utf8')!==code){console.error('src/generated/side-story-app.js is stale; run npm run build');process.exit(1);}
  console.log('generated app is current');
 }else{writeFileSync(target,code);console.log('wrote src/generated/side-story-app.js',code.length,'chars');}
}
